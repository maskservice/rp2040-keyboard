def validate_config(cfg: PadConfig) -> list[str]:
    errors = []
    used = {}

    for i, k in enumerate(cfg.keys):
        g = k.gpio
        if g not in AVAILABLE_GPIOS:
            errors.append(f"Przycisk {i+1}: GP{g} nie istnieje na RP2040")
        if g in used:
            errors.append(f"Przycisk {i+1}: GP{g} już użyty przez {used[g]}")
        used[g] = f"Przycisk {i+1}"
        if k.keycode not in KEYCODES:
            errors.append(f"Przycisk {i+1}: nieznany keycode '{k.keycode}'")
        if k.modifier not in MODIFIERS:
            errors.append(f"Przycisk {i+1}: nieznany modifier '{k.modifier}'")

    enc = cfg.encoder
    for name, g in [("CLK", enc.clk_gpio), ("DT", enc.dt_gpio), ("SW", enc.sw_gpio)]:
        if g not in AVAILABLE_GPIOS:
            errors.append(f"Enkoder {name}: GP{g} nie istnieje")
        if g in used:
            errors.append(f"Enkoder {name}: GP{g} już użyty przez {used[g]}")
        used[g] = f"Enkoder {name}"

    if not (1 <= enc.scroll_speed <= 20):
        errors.append("scroll_speed musi być 1–20")
    if not (5 <= enc.debounce_ms <= 500):
        errors.append("debounce_ms musi być 5–500")

    return errors

