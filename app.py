app = FastAPI(title="RP2040-One Keypad Configurator", version="1.0.0")

OUTPUT_DIR = Path("output")
OUTPUT_DIR.mkdir(exist_ok=True)


@app.get("/", response_class=HTMLResponse)
async def index():
    return FRONTEND_HTML


@app.get("/api/defaults")
async def api_defaults():
    cfg = PadConfig()
    return {
        "keys": [asdict(k) for k in cfg.keys],
        "encoder": asdict(cfg.encoder),
        "available_keycodes": list(KEYCODES.keys()),
        "available_modifiers": list(MODIFIERS.keys()),
        "available_gpios": AVAILABLE_GPIOS,
    }


@app.post("/api/validate")
async def api_validate(request: Request):
    data = await request.json()
    cfg = _parse_config(data)
    errors = validate_config(cfg)
    return {"valid": len(errors) == 0, "errors": errors}


@app.post("/api/generate")
async def api_generate(request: Request):
    data = await request.json()
    cfg = _parse_config(data)
    errors = validate_config(cfg)
    if errors:
        return JSONResponse({"errors": errors}, status_code=400)

    code = generate_code_py(cfg)
    boot = BOOT_PY

    OUTPUT_DIR.mkdir(exist_ok=True)
    (OUTPUT_DIR / "code.py").write_text(code)
    (OUTPUT_DIR / "boot.py").write_text(boot)

    return {
        "code_py": code,
        "boot_py": boot,
        "message": "Pliki wygenerowane i zapisane w output/"
    }


@app.get("/api/download/code.py", response_class=PlainTextResponse)
async def download_code():
    p = OUTPUT_DIR / "code.py"
    if not p.exists():
        return PlainTextResponse("Najpierw wygeneruj config", status_code=404)
    return PlainTextResponse(p.read_text(), media_type="text/x-python",
                             headers={"Content-Disposition": "attachment; filename=code.py"})


@app.get("/api/download/boot.py", response_class=PlainTextResponse)
async def download_boot():
    return PlainTextResponse(BOOT_PY, media_type="text/x-python",
                             headers={"Content-Disposition": "attachment; filename=boot.py"})


def _parse_config(data: dict) -> PadConfig:
    keys = []
    for k in data.get("keys", []):
        keys.append(KeyConfig(
            gpio=int(k["gpio"]),
            keycode=str(k["keycode"]),
            modifier=str(k.get("modifier", "CTRL")),
            label=str(k.get("label", "")),
        ))
    enc_data = data.get("encoder", {})
    enc = EncoderConfig(
        clk_gpio=int(enc_data.get("clk_gpio", 9)),
        dt_gpio=int(enc_data.get("dt_gpio", 10)),
        sw_gpio=int(enc_data.get("sw_gpio", 11)),
        scroll_speed=int(enc_data.get("scroll_speed", 2)),
        debounce_ms=int(enc_data.get("debounce_ms", 50)),
    )
    return PadConfig(keys=keys, encoder=enc)


