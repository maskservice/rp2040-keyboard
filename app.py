def generate_code_py(cfg: PadConfig) -> str:
    key_lines = []
    for k in cfg.keys:
        kc = KEYCODES.get(k.keycode, "Keycode.ONE")
        comment = f"# {k.label}" if k.label else ""
        key_lines.append(f"    (board.GP{k.gpio}, {kc}),  {comment}")

    keys_block = "\n".join(key_lines)

    # Modifier logic
    mod_set = {k.modifier for k in cfg.keys}
    if len(mod_set) == 1:
        mod = list(mod_set)[0]
        mod_val = MODIFIERS.get(mod)
        if mod_val:
            press_line = f"keyboard.press({mod_val}, key['keycode'])"
            release_line = f"keyboard.release({mod_val}, key['keycode'])"
        else:
            press_line = "keyboard.press(key['keycode'])"
            release_line = "keyboard.release(key['keycode'])"
    else:
        # Per-key modifier stored in array — more complex variant
        press_line = "keyboard.press(key['modifier'], key['keycode'])" if any(
            MODIFIERS.get(k.modifier) for k in cfg.keys
        ) else "keyboard.press(key['keycode'])"
        release_line = press_line.replace("press", "release")

    enc = cfg.encoder

    return textwrap.dedent(f'''\
"""
RP2040-One HID Keypad + Encoder Mouse
Generated by Web Configurator — Softreck / Prototypowanie.pl
"""

import time
import board
import digitalio
import usb_hid
from adafruit_hid.keyboard import Keyboard
from adafruit_hid.keycode import Keycode
from adafruit_hid.mouse import Mouse

# ── Konfiguracja klawiszy ──
KEY_PINS = [
{keys_block}
]

# ── Konfiguracja enkodera ──
ENCODER_CLK_PIN = board.GP{enc.clk_gpio}
ENCODER_DT_PIN  = board.GP{enc.dt_gpio}
ENCODER_SW_PIN  = board.GP{enc.sw_gpio}
SCROLL_SPEED    = {enc.scroll_speed}
DEBOUNCE_MS     = {enc.debounce_ms}
ENCODER_DEBOUNCE_MS = 5

# ── HID init ──
keyboard = Keyboard(usb_hid.devices)
mouse = Mouse(usb_hid.devices)

# ── Piny klawiszy ──
keys = []
for pin, keycode in KEY_PINS:
    dio = digitalio.DigitalInOut(pin)
    dio.direction = digitalio.Direction.INPUT
    dio.pull = digitalio.Pull.UP
    keys.append(dict(pin=dio, keycode=keycode, last_state=True, last_change=0))

# ── Piny enkodera ──
encoder_clk = digitalio.DigitalInOut(ENCODER_CLK_PIN)
encoder_clk.direction = digitalio.Direction.INPUT
encoder_clk.pull = digitalio.Pull.UP

encoder_dt = digitalio.DigitalInOut(ENCODER_DT_PIN)
encoder_dt.direction = digitalio.Direction.INPUT
encoder_dt.pull = digitalio.Pull.UP

encoder_sw = digitalio.DigitalInOut(ENCODER_SW_PIN)
encoder_sw.direction = digitalio.Direction.INPUT
encoder_sw.pull = digitalio.Pull.UP

encoder_last_clk = encoder_clk.value
encoder_sw_last = True
encoder_sw_last_change = 0

# ── Główna pętla ──
while True:
    now = time.monotonic() * 1000

    for key in keys:
        current = key['pin'].value
        if current != key['last_state']:
            if (now - key['last_change']) > DEBOUNCE_MS:
                key['last_change'] = now
                key['last_state'] = current
                if not current:
                    {press_line}
                else:
                    {release_line}

    clk_val = encoder_clk.value
    if clk_val != encoder_last_clk:
        dt_val = encoder_dt.value
        if dt_val != clk_val:
            mouse.move(wheel=SCROLL_SPEED)
        else:
            mouse.move(wheel=-SCROLL_SPEED)
        encoder_last_clk = clk_val

    sw_val = encoder_sw.value
    if sw_val != encoder_sw_last:
        if (now - encoder_sw_last_change) > DEBOUNCE_MS:
            encoder_sw_last_change = now
            encoder_sw_last = sw_val
            if not sw_val:
                mouse.press(Mouse.MIDDLE_BUTTON)
            else:
                mouse.release(Mouse.MIDDLE_BUTTON)

    time.sleep(0.001)
''')


